"""Async (TD §11.5): SQS jobs and outbox with DLQs, the dispatcher, the watcher and the sweeper.

Queue names are fixed (``wf-<env>-jobs``, ``wf-<env>-outbox``) because the MCP stack
derives their URLs from config. Visibility timeouts exceed the dispatcher's 120 s timeout.
"""

from __future__ import annotations

from typing import Any

from aws_cdk import CfnOutput, Duration, Stack
from aws_cdk import aws_events as events
from aws_cdk import aws_events_targets as targets
from aws_cdk import aws_iam as iam
from aws_cdk import aws_lambda_event_sources as sources
from aws_cdk import aws_secretsmanager as sm
from aws_cdk import aws_sqs as sqs
from constructs import Construct

from ..common import PythonLambda
from ..config import EnvConfig
from .agents import AgentsStack
from .auth import AuthStack
from .data import DataStack
from .net import NetStack


class AsyncStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        cfg: EnvConfig,
        net: NetStack,
        data: DataStack,
        auth: AuthStack,
        agents: AgentsStack | None,
        **kwargs: Any,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        p = cfg.prefix
        self.jobs_dlq = sqs.Queue(
            self, "JobsDlq", queue_name=f"{p}-jobs-dlq", retention_period=Duration.days(14)
        )
        self.jobs = sqs.Queue(
            self,
            "Jobs",
            queue_name=f"{p}-jobs",
            visibility_timeout=Duration.seconds(180),
            enforce_ssl=True,
            dead_letter_queue=sqs.DeadLetterQueue(queue=self.jobs_dlq, max_receive_count=3),
        )
        self.outbox_dlq = sqs.Queue(
            self, "OutboxDlq", queue_name=f"{p}-outbox-dlq", retention_period=Duration.days(14)
        )
        self.outbox = sqs.Queue(
            self,
            "Outbox",
            queue_name=f"{p}-outbox",
            visibility_timeout=Duration.seconds(130),
            enforce_ssl=True,
            dead_letter_queue=sqs.DeadLetterQueue(queue=self.outbox_dlq, max_receive_count=5),
        )

        # Filled in after deploy (README, Deploy). The dispatcher's client secret is generated by Auth.
        self.slack_secret = sm.Secret(self, "SlackSecret", secret_name=f"{p}/slack/webhook")
        self.dispatcher_secret = auth.dispatcher_secret

        common = {
            "WF_DB_SECRET_ARN": data.app_secret.secret_arn,
            "WF_JOBS_QUEUE_URL": self.jobs.queue_url,
            "WF_OUTBOX_QUEUE_URL": self.outbox.queue_url,
        }
        vpc = {"vpc": net.vpc, "security_groups": [net.lambda_sg]}
        dispatcher_env = {
            **common,
            "WF_SLACK_SECRET_ARN": self.slack_secret.secret_arn,
            "WF_DISPATCHER_CLIENT_SECRET_ARN": self.dispatcher_secret.secret_arn,
        }
        if agents is not None:  # models enabled: memory events, Haiku drafts, the agent runtime
            dispatcher_env |= {"WF_MEMORY_ID": agents.memory_id, "WF_HAIKU_MODEL_ID": cfg.models.haiku}
            if agents.runtime_arn:
                dispatcher_env["WF_AGENT_RUNTIME_ARN"] = agents.runtime_arn
        self.dispatcher = PythonLambda(
            self,
            "Dispatcher",
            cfg=cfg,
            name="dispatcher",
            bundle="workers",
            handler="workers.dispatcher.handler",
            memory_size=512,
            timeout=Duration.seconds(120),
            reserved_concurrency=3,
            environment=dispatcher_env,
            **vpc,
        ).function
        for queue in (self.jobs, self.outbox):
            self.dispatcher.add_event_source(
                sources.SqsEventSource(queue, batch_size=1, report_batch_item_failures=True)
            )
            queue.grant_send_messages(self.dispatcher)  # follow-up rows (DD §8.4)
        for secret in (data.app_secret, self.slack_secret, self.dispatcher_secret):
            secret.grant_read(self.dispatcher)
        if agents is not None:
            if agents.runtime_arn:
                self.dispatcher.add_to_role_policy(
                    iam.PolicyStatement(
                        actions=["bedrock-agentcore:InvokeAgentRuntime"],
                        resources=[agents.runtime_arn, f"{agents.runtime_arn}/*"],
                    )
                )
            self.dispatcher.add_to_role_policy(
                iam.PolicyStatement(  # follow-up drafts (Haiku-class, Converse)
                    actions=["bedrock:InvokeModel", "bedrock:Converse"],
                    resources=[
                        f"arn:aws:bedrock:*:{cfg.account}:inference-profile/{cfg.models.haiku}",
                        "arn:aws:bedrock:*::foundation-model/*",
                    ],
                )
            )
            self.dispatcher.add_to_role_policy(
                iam.PolicyStatement(actions=["bedrock-agentcore:CreateEvent"], resources=[agents.memory_arn])
            )

        self.watcher = PythonLambda(
            self,
            "Watcher",
            cfg=cfg,
            name="watcher",
            bundle="workers",
            handler="workers.watcher.handler",
            timeout=Duration.seconds(60),
            environment=common,
            **vpc,
        ).function
        self.sweeper = PythonLambda(
            self,
            "Sweeper",
            cfg=cfg,
            name="sweeper",
            bundle="workers",
            handler="workers.sweeper.handler",
            timeout=Duration.seconds(30),
            environment=common,
            **vpc,
        ).function
        for fn in (self.watcher, self.sweeper):
            data.app_secret.grant_read(fn)
            self.outbox.grant_send_messages(fn)
        self.sweeper.add_to_role_policy(
            iam.PolicyStatement(actions=["sqs:SendMessage"], resources=[self.jobs.queue_arn])
        )
        events.Rule(
            self,
            "Every15",
            schedule=events.Schedule.rate(Duration.minutes(15)),
            targets=[targets.LambdaFunction(self.watcher)],
        )
        events.Rule(
            self,
            "Every1",
            schedule=events.Schedule.rate(Duration.minutes(1)),
            targets=[targets.LambdaFunction(self.sweeper)],
        )
        CfnOutput(self, "SlackSecretName", value=self.slack_secret.secret_name)
