"""Async (TD §11.5): SQS jobs and outbox with DLQs, the dispatcher, the watcher and the sweeper.

Queue names are fixed (``wf-<env>-jobs``, ``wf-<env>-outbox``) because the MCP stack
derives their URLs from config. Visibility timeouts exceed the dispatcher's 120 s timeout.
With ``agents_host: lambda`` the triage agents run here too, as a function the dispatcher
invokes (ADR-023). It is outside the VPC: it reaches only the MCP server and the model.

With ``compute: ecs`` (ADR-025) the four functions are one Fargate service running
``workers.service`` (both queue consumers, the sweeper, the watcher and the canary, with every grant
they had), and the agents are a second service the workers call at
``http://triage.<prefix>.internal:8080/invocations``. The queues are new ones (``…-svc``,
``EnvConfig.queue_name``), out of reach of the event source mappings a blocked Lambda leaves behind.
"""

from __future__ import annotations

from typing import Any

from aws_cdk import CfnOutput, Duration, Stack
from aws_cdk import aws_events as events
from aws_cdk import aws_events_targets as targets
from aws_cdk import aws_iam as iam
from aws_cdk import aws_lambda as lambda_
from aws_cdk import aws_lambda_event_sources as sources
from aws_cdk import aws_secretsmanager as sm
from aws_cdk import aws_sqs as sqs
from constructs import Construct

from ..common import HTTP_PORT, NAMESPACE, Container, PythonLambda, bedrock_arns, gemini_access
from ..config import EnvConfig
from .agents import AgentsStack
from .auth import AuthStack
from .data import DataStack
from .net import NetStack

BEDROCK_ALL = [
    "bedrock:InvokeModel",
    "bedrock:InvokeModelWithResponseStream",
    "bedrock:Converse",
    "bedrock:ConverseStream",
]


class AsyncStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        cfg: EnvConfig,
        net: NetStack,
        data: DataStack,
        auth: AuthStack,
        agents: AgentsStack | None,
        **kwargs: Any,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        self.jobs_dlq = sqs.Queue(
            self, "JobsDlq", queue_name=cfg.queue_name("jobs-dlq"), retention_period=Duration.days(14)
        )
        self.jobs = sqs.Queue(
            self,
            "Jobs",
            queue_name=cfg.queue_name("jobs"),
            visibility_timeout=Duration.seconds(180),
            enforce_ssl=True,
            dead_letter_queue=sqs.DeadLetterQueue(queue=self.jobs_dlq, max_receive_count=3),
        )
        self.outbox_dlq = sqs.Queue(
            self, "OutboxDlq", queue_name=cfg.queue_name("outbox-dlq"), retention_period=Duration.days(14)
        )
        self.outbox = sqs.Queue(
            self,
            "Outbox",
            queue_name=cfg.queue_name("outbox"),
            visibility_timeout=Duration.seconds(130),
            enforce_ssl=True,
            dead_letter_queue=sqs.DeadLetterQueue(queue=self.outbox_dlq, max_receive_count=5),
        )

        # Filled in after deploy (README, Deploy). The dispatcher's client secret is generated by Auth.
        self.slack_secret = sm.Secret(self, "SlackSecret", secret_name=f"{cfg.prefix}/slack/webhook")
        self.dispatcher_secret = auth.dispatcher_secret

        self.common_env = {
            "WF_DB_SECRET_ARN": data.app_secret.secret_arn,
            "WF_JOBS_QUEUE_URL": self.jobs.queue_url,
            "WF_OUTBOX_QUEUE_URL": self.outbox.queue_url,
        }
        self.dispatcher_env = {
            **self.common_env,
            "WF_SLACK_SECRET_ARN": self.slack_secret.secret_arn,
            "WF_DISPATCHER_CLIENT_SECRET_ARN": self.dispatcher_secret.secret_arn,
        }
        if cfg.models_enabled:  # follow-up drafts on the fast model
            self.dispatcher_env["WF_HAIKU_MODEL_ID"] = cfg.models.haiku
        if agents is not None:  # AgentCore: memory events and the agent runtime
            self.dispatcher_env["WF_MEMORY_ID"] = agents.memory_id
            if agents.runtime_arn:
                self.dispatcher_env["WF_AGENT_RUNTIME_ARN"] = agents.runtime_arn
        self.triage: lambda_.Function | Container | None = None
        if cfg.ecs:
            self._containers(cfg, net, data, auth, agents)
        else:
            self._functions(cfg, net, data, agents)
        CfnOutput(self, "SlackSecretName", value=self.slack_secret.secret_name)
        # The Ops stack read the dead-letter queues' names through these exports until it named them
        # itself (ADR-025). An export another stack still imports can't change or disappear, and this
        # stack deploys first, so the old names stay exported, as plain strings, for an Ops stack
        # deployed before the change.
        for dlq, export in (
            ("jobs-dlq", "ExportsOutputFnGetAttJobsDlqB53173A1QueueName299FCEF1"),
            ("outbox-dlq", "ExportsOutputFnGetAttOutboxDlqFF3CB47FQueueName3435D3EA"),
        ):
            CfnOutput(
                self,
                f"Legacy{export[-8:]}",
                value=f"{cfg.prefix}-{dlq}",
                export_name=f"{self.stack_name}:{export}",
            )

    def _triage_access(self, cfg: EnvConfig, triage: lambda_.Function | Container) -> None:
        if cfg.models_enabled:
            triage.add_to_role_policy(
                iam.PolicyStatement(
                    actions=BEDROCK_ALL, resources=bedrock_arns(cfg, cfg.models.sonnet, cfg.models.haiku)
                )
            )
        if cfg.gemini_enabled:
            gemini_access(self, cfg, triage)

    def _dispatcher_access(
        self, cfg: EnvConfig, data: DataStack, agents: AgentsStack | None, fn: lambda_.Function | Container
    ) -> None:
        """What delivering outbox rows needs, on either compute."""
        for queue in (self.jobs, self.outbox):
            queue.grant_send_messages(fn)  # follow-up rows (DD §8.4)
        for secret in (data.app_secret, self.slack_secret, self.dispatcher_secret):
            secret.grant_read(fn)
        if cfg.gemini_enabled:  # follow-up drafts: after Bedrock, or alone where models are off (ADR-023)
            gemini_access(self, cfg, fn)
        if cfg.models_enabled:
            fn.add_to_role_policy(
                iam.PolicyStatement(  # follow-up drafts (the fast model, Converse)
                    actions=["bedrock:InvokeModel", "bedrock:Converse"],
                    resources=bedrock_arns(cfg, cfg.models.haiku),
                )
            )
        if agents is not None:
            if agents.runtime_arn:
                fn.add_to_role_policy(
                    iam.PolicyStatement(
                        actions=["bedrock-agentcore:InvokeAgentRuntime"],
                        resources=[agents.runtime_arn, f"{agents.runtime_arn}/*"],
                    )
                )
            fn.add_to_role_policy(
                iam.PolicyStatement(actions=["bedrock-agentcore:CreateEvent"], resources=[agents.memory_arn])
            )

    def _containers(
        self, cfg: EnvConfig, net: NetStack, data: DataStack, auth: AuthStack, agents: AgentsStack | None
    ) -> None:
        env = dict(self.dispatcher_env)
        if cfg.triage_lambda:  # the agents as their own service (ADR-023, ADR-025)
            triage_env = (
                {"WF_SONNET_MODEL_ID": cfg.models.sonnet, "WF_HAIKU_MODEL_ID": cfg.models.haiku}
                if cfg.models_enabled
                else {}
            )
            triage = Container(
                self,
                "Triage",
                cfg=cfg,
                name="triage",
                bundle="agents",
                command=["python", "-m", "agents.main"],
                memory_mib=1024,
                # BedrockAgentCoreApp listens on 0.0.0.0 inside a container (DOCKER_CONTAINER, friction 3)
                environment={
                    **triage_env,
                    "DOCKER_CONTAINER": "1",
                    "WF_AGENT_PORT": str(HTTP_PORT),
                },
                http=True,
                health_path="/ping",
            )
            self._triage_access(cfg, triage)
            triage.service(net, discovery="triage")
            self.triage = triage
            env["WF_AGENT_URL"] = f"http://triage.{cfg.prefix}.internal:{HTTP_PORT}/invocations"
        canary_secret = auth.canary_secret  # {"email","password"}, generated by Auth, login set by the seeder
        workers = Container(
            self,
            "Workers",
            cfg=cfg,
            name="workers",
            bundle="workers",
            command=["python", "-m", "workers.service"],
            environment={
                **env,
                "WF_CANARY_SECRET_ARN": canary_secret.secret_arn,
                "WF_HARNESS_REDIRECT_URI": f"{cfg.harness_url}/oauth/callback",
                "WF_METRICS_API": "true",  # stdout is not read as embedded metric format on ECS
            },
        )
        self._dispatcher_access(cfg, data, agents, workers)
        for queue in (self.jobs, self.outbox):
            queue.grant_consume_messages(workers)
        canary_secret.grant_read(workers)
        workers.add_to_role_policy(
            iam.PolicyStatement(
                actions=["cloudwatch:PutMetricData"],
                resources=["*"],  # PutMetricData has no resource type; the condition narrows it
                conditions={"StringEquals": {"cloudwatch:namespace": NAMESPACE}},
            )
        )
        # One consumer and one scheduler: the new task starts once the old one has stopped.
        workers.service(net, rolling=False)
        self.workers = workers

    def _functions(self, cfg: EnvConfig, net: NetStack, data: DataStack, agents: AgentsStack | None) -> None:
        vpc = {"vpc": net.vpc, "security_groups": [net.lambda_sg]}
        if cfg.triage_lambda:  # the agents as a plain function (ADR-023)
            triage_env = (
                {"WF_SONNET_MODEL_ID": cfg.models.sonnet, "WF_HAIKU_MODEL_ID": cfg.models.haiku}
                if cfg.models_enabled
                else {}
            )
            triage = PythonLambda(
                self,
                "Triage",
                cfg=cfg,
                name="triage",
                bundle="agents",
                handler="agents.handler.handler",
                memory_size=1024,
                timeout=Duration.seconds(95),  # the agents stop themselves at 90 s
                reserved_concurrency=3,  # MAX_ACTIVE_JOBS
                environment=triage_env,
            ).function
            self._triage_access(cfg, triage)
            self.dispatcher_env["WF_AGENT_FUNCTION"] = triage.function_name
            self.triage = triage
        self.dispatcher = PythonLambda(
            self,
            "Dispatcher",
            cfg=cfg,
            name="dispatcher",
            bundle="workers",
            handler="workers.dispatcher.handler",
            memory_size=512,
            timeout=Duration.seconds(120),
            reserved_concurrency=3,
            environment=self.dispatcher_env,
            **vpc,
        ).function
        for queue in (self.jobs, self.outbox):
            self.dispatcher.add_event_source(
                sources.SqsEventSource(queue, batch_size=1, report_batch_item_failures=True)
            )
        self._dispatcher_access(cfg, data, agents, self.dispatcher)
        if isinstance(self.triage, lambda_.Function):
            self.triage.grant_invoke(self.dispatcher)

        self.watcher = PythonLambda(
            self,
            "Watcher",
            cfg=cfg,
            name="watcher",
            bundle="workers",
            handler="workers.watcher.handler",
            timeout=Duration.seconds(60),
            environment=self.common_env,
            **vpc,
        ).function
        self.sweeper = PythonLambda(
            self,
            "Sweeper",
            cfg=cfg,
            name="sweeper",
            bundle="workers",
            handler="workers.sweeper.handler",
            timeout=Duration.seconds(30),
            environment=self.common_env,
            **vpc,
        ).function
        for fn in (self.watcher, self.sweeper):
            data.app_secret.grant_read(fn)
            self.outbox.grant_send_messages(fn)
        self.sweeper.add_to_role_policy(
            iam.PolicyStatement(actions=["sqs:SendMessage"], resources=[self.jobs.queue_arn])
        )
        events.Rule(
            self,
            "Every15",
            schedule=events.Schedule.rate(Duration.minutes(15)),
            targets=[targets.LambdaFunction(self.watcher)],
        )
        events.Rule(
            self,
            "Every1",
            schedule=events.Schedule.rate(Duration.minutes(1)),
            targets=[targets.LambdaFunction(self.sweeper)],
        )
