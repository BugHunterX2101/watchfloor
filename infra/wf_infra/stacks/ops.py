"""Ops (DD §19.3, TD §16.3–16.4): canary, alarms to SNS email, the ``wf-<env>`` dashboard, budgets.

Metric names and dimensions match what the code emits: ``ToolLatencyMs{tool}`` from the
MCP server, ``CanarySuccess{service}``, ``OutboxDead/OutboxBacklog/TriageTimedOut{service}``
from the sweeper and ``OutboxDeadLettered/OutboxSent{service,kind}`` from the dispatcher.
"""

from __future__ import annotations

from typing import Any

from aws_cdk import Duration, Stack
from aws_cdk import aws_budgets as budgets
from aws_cdk import aws_cloudwatch as cw
from aws_cdk import aws_cloudwatch_actions as cw_actions
from aws_cdk import aws_events as events
from aws_cdk import aws_events_targets as targets
from aws_cdk import aws_sns as sns
from aws_cdk import aws_sns_subscriptions as subs
from constructs import Construct

from ..common import NAMESPACE, PythonLambda
from ..config import EnvConfig
from .async_ import AsyncStack
from .auth import AuthStack
from .mcp import McpStack

HOT_TOOLS = ("get_risk_briefing", "explain_deal_risk")
FIVE_MIN = Duration.minutes(5)


def _metric(name: str, stat: str = "Sum", period: Duration = FIVE_MIN, **dims: str) -> cw.Metric:
    return cw.Metric(
        namespace=NAMESPACE, metric_name=name, dimensions_map=dims, statistic=stat, period=period
    )


class OpsStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        cfg: EnvConfig,
        auth: AuthStack,
        mcp: McpStack,
        asyncs: AsyncStack,
        **kwargs: Any,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        p = cfg.prefix
        topic = sns.Topic(self, "Alerts", topic_name=f"{p}-alerts")
        topic.add_subscription(subs.EmailSubscription(cfg.alert_email))
        action = cw_actions.SnsAction(topic)

        # Canary (DD §17): sign in through the harness client, list tools, fetch a briefing. No VPC.
        canary_secret = auth.canary_secret  # {"email","password"}, generated by Auth, login set by the seeder
        canary = PythonLambda(
            self,
            "Canary",
            cfg=cfg,
            name="canary",
            bundle="workers",
            handler="workers.canary.handler",
            timeout=Duration.seconds(30),
            environment={
                "WF_CANARY_SECRET_ARN": canary_secret.secret_arn,
                "WF_HARNESS_REDIRECT_URI": f"{cfg.harness_url}/oauth/callback",
            },
        ).function
        canary_secret.grant_read(canary)
        events.Rule(
            self, "Every5", schedule=events.Schedule.rate(FIVE_MIN), targets=[targets.LambdaFunction(canary)]
        )

        def alarm(
            construct_id: str,
            name: str,
            metric: cw.IMetric,
            threshold: float,
            periods: int,
            *,
            op: cw.ComparisonOperator = cw.ComparisonOperator.GREATER_THAN_THRESHOLD,
            missing: cw.TreatMissingData = cw.TreatMissingData.NOT_BREACHING,
        ) -> cw.Alarm:
            a = cw.Alarm(
                self,
                f"{construct_id}Alarm",
                alarm_name=f"{p}-{name}",
                metric=metric,
                threshold=threshold,
                evaluation_periods=periods,
                comparison_operator=op,
                treat_missing_data=missing,
            )
            a.add_alarm_action(action)
            return a

        for tool in HOT_TOOLS:
            alarm(
                f"HotP95{tool}",
                f"hot-p95-{tool.replace('_', '-')}",
                _metric("ToolLatencyMs", "p95", tool=tool),
                300,
                2,
            )
        api = mcp.api
        five_xx = cw.MathExpression(
            expression="100 * errors / MAX([requests, 1])",
            using_metrics={
                "errors": api.metric_server_error(period=FIVE_MIN, statistic="Sum"),
                "requests": api.metric_count(period=FIVE_MIN, statistic="Sum"),
            },
            period=FIVE_MIN,
            label="5xx %",
        )
        alarm("FiveXx", "5xx", five_xx, 0.5, 1)
        spillover = mcp.alias.metric(
            "ProvisionedConcurrencySpilloverInvocations", period=FIVE_MIN, statistic="Sum"
        )
        alarm("Spillover", "spillover", spillover, 0, 3)
        alarm(
            "Canary",
            "canary",
            _metric("CanarySuccess", "Minimum", service="canary"),
            1,
            2,
            op=cw.ComparisonOperator.LESS_THAN_THRESHOLD,
            missing=cw.TreatMissingData.BREACHING,
        )
        alarm(
            "JobsDlq",
            "jobs-dlq",
            asyncs.jobs_dlq.metric_approximate_number_of_messages_visible(
                period=FIVE_MIN, statistic="Maximum"
            ),
            0,
            1,
        )
        alarm(
            "OutboxDlq",
            "outbox-dlq",
            asyncs.outbox_dlq.metric_approximate_number_of_messages_visible(
                period=FIVE_MIN, statistic="Maximum"
            ),
            0,
            1,
        )
        alarm("OutboxDead", "outbox-dead", _metric("OutboxDead", "Maximum", service="sweeper"), 0, 1)
        hour = Duration.hours(1)
        triage_fail = cw.MathExpression(
            expression="100 * (dead + timedout) / MAX([sent + dead + timedout, 1])",
            using_metrics={
                "dead": _metric("OutboxDeadLettered", period=hour, service="dispatcher", kind="triage_job"),
                "sent": _metric("OutboxSent", period=hour, service="dispatcher", kind="triage_job"),
                "timedout": _metric("TriageTimedOut", period=hour, service="sweeper"),
            },
            period=hour,
            label="triage failure %",
        )
        alarm("TriageFail", "triage-fail", triage_fail, 10, 1)

        dash = cw.Dashboard(self, "Dashboard", dashboard_name=p)
        dash.add_widgets(
            cw.GraphWidget(
                title="Hot path: ToolLatencyMs p95",
                left=[_metric("ToolLatencyMs", "p95", tool=t) for t in HOT_TOOLS],
                width=12,
            ),
            cw.GraphWidget(
                title="Hot path: 5xx % and spillover", left=[five_xx], right=[spillover], width=12
            ),
        )
        dash.add_widgets(
            cw.GraphWidget(title="Warm path: triage failure %", left=[triage_fail], width=12),
            cw.GraphWidget(
                title="Cold path: outbox",
                left=[
                    _metric("OutboxBacklog", "Maximum", service="sweeper"),
                    _metric("OutboxDead", "Maximum", service="sweeper"),
                ],
                right=[_metric("WatcherDurationMs", "Maximum", service="watcher")],
                width=12,
            ),
        )
        dash.add_widgets(
            cw.GraphWidget(
                title="Availability: canary",
                left=[_metric("CanarySuccess", "Average", service="canary")],
                right=[_metric("CanaryLatencyMs", "p95", service="canary")],
                width=24,
            )
        )

        # Budgets (DD §25): one account-wide monthly cost budget, e-mailing at each threshold. Account-wide
        # because a tag filter reads $0 until the tag is activated for cost allocation; only one
        # environment's config should list thresholds (dev.yaml), or the e-mails arrive twice.
        if not cfg.budgets_usd:
            return
        budgets.CfnBudget(
            self,
            "Budget",
            budget=budgets.CfnBudget.BudgetDataProperty(
                budget_name="watchfloor-cost",
                budget_type="COST",
                time_unit="MONTHLY",
                budget_limit=budgets.CfnBudget.SpendProperty(amount=max(cfg.budgets_usd), unit="USD"),
                # Usage before credits: on an account paid for by credits, spend net of them reads $0.
                cost_types=budgets.CfnBudget.CostTypesProperty(include_credit=False, include_refund=False),
            ),
            notifications_with_subscribers=[
                budgets.CfnBudget.NotificationWithSubscribersProperty(
                    notification=budgets.CfnBudget.NotificationProperty(
                        comparison_operator="GREATER_THAN",
                        notification_type="ACTUAL",
                        threshold=amount,
                        threshold_type="ABSOLUTE_VALUE",
                    ),
                    subscribers=[
                        budgets.CfnBudget.SubscriberProperty(
                            subscription_type="EMAIL", address=cfg.alert_email
                        )
                    ],
                )
                for amount in cfg.budgets_usd
            ],
        )
