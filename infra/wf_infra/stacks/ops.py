"""Ops (DD §19.3, TD §16.3–16.4): canary, alarms to SNS email, the ``wf-<env>`` dashboard, budgets.

Metric names and dimensions match what the code emits: ``ToolLatencyMs{tool}`` from the
MCP server, ``CanarySuccess{service}``, ``OutboxDead/OutboxBacklog/TriageTimedOut{service}``
from the sweeper and ``OutboxDeadLettered/OutboxSent{service,kind}`` from the dispatcher.
"""

from __future__ import annotations

from typing import Any

from aws_cdk import Duration, Stack
from aws_cdk import aws_budgets as budgets
from aws_cdk import aws_cloudwatch as cw
from aws_cdk import aws_cloudwatch_actions as cw_actions
from aws_cdk import aws_events as events
from aws_cdk import aws_events_targets as targets
from aws_cdk import aws_sns as sns
from aws_cdk import aws_sns_subscriptions as subs
from constructs import Construct

from ..common import NAMESPACE, PythonLambda
from ..config import EnvConfig
from .async_ import AsyncStack
from .auth import AuthStack
from .data import DataStack
from .mcp import McpStack

HOT_TOOLS = ("get_risk_briefing", "explain_deal_risk")
FIVE_MIN = Duration.minutes(5)
GIB = 1024**3
INSTANCE_GIB = {"micro": 1, "small": 2, "medium": 4, "large": 8, "xlarge": 16, "2xlarge": 32}


def db_connection_alarm_level(instance_class: str) -> int:
    """80% of what an RDS Postgres of this size allows: about 80 connections per GiB of memory
    (a t4g.micro allows 87), so the alarm rings while there is still room to act."""
    return int(0.8 * 80 * INSTANCE_GIB.get(instance_class.rsplit(".", 1)[-1], 1))


def _metric(name: str, stat: str = "Sum", period: Duration = FIVE_MIN, **dims: str) -> cw.Metric:
    return cw.Metric(
        namespace=NAMESPACE, metric_name=name, dimensions_map=dims, statistic=stat, period=period
    )


class OpsStack(Stack):
    def __init__(
        self,
        scope: Construct,
        construct_id: str,
        *,
        cfg: EnvConfig,
        data: DataStack,
        auth: AuthStack,
        mcp: McpStack,
        asyncs: AsyncStack,
        **kwargs: Any,
    ) -> None:
        super().__init__(scope, construct_id, **kwargs)
        p = cfg.prefix
        topic = sns.Topic(self, "Alerts", topic_name=f"{p}-alerts")
        topic.add_subscription(subs.EmailSubscription(cfg.alert_email))
        action = cw_actions.SnsAction(topic)

        # Canary (DD §17): sign in through the harness client, list tools, fetch a briefing. No VPC.
        # On ECS (ADR-025) the workers service runs it every five minutes instead (Async stack).
        if not cfg.ecs:
            canary_secret = auth.canary_secret  # {"email","password"}, generated by Auth, login by the seeder
            canary = PythonLambda(
                self,
                "Canary",
                cfg=cfg,
                name="canary",
                bundle="workers",
                handler="workers.canary.handler",
                timeout=Duration.seconds(30),
                environment={
                    "WF_CANARY_SECRET_ARN": canary_secret.secret_arn,
                    "WF_HARNESS_REDIRECT_URI": f"{cfg.harness_url}/oauth/callback",
                },
            ).function
            canary_secret.grant_read(canary)
            events.Rule(
                self,
                "Every5",
                schedule=events.Schedule.rate(FIVE_MIN),
                targets=[targets.LambdaFunction(canary)],
            )

        def alarm(
            construct_id: str,
            name: str,
            metric: cw.IMetric,
            threshold: float,
            periods: int,
            *,
            op: cw.ComparisonOperator = cw.ComparisonOperator.GREATER_THAN_THRESHOLD,
            missing: cw.TreatMissingData = cw.TreatMissingData.NOT_BREACHING,
        ) -> cw.Alarm:
            a = cw.Alarm(
                self,
                f"{construct_id}Alarm",
                alarm_name=f"{p}-{name}",
                metric=metric,
                threshold=threshold,
                evaluation_periods=periods,
                comparison_operator=op,
                treat_missing_data=missing,
            )
            a.add_alarm_action(action)
            return a

        for tool in HOT_TOOLS:
            alarm(
                f"HotP95{tool}",
                f"hot-p95-{tool.replace('_', '-')}",
                _metric("ToolLatencyMs", "p95", tool=tool),
                300,
                2,
            )
        api = mcp.api
        five_xx = cw.MathExpression(
            # IF guards the division: alarm math refuses MAX over a [series, scalar] array.
            expression="IF(requests > 0, 100 * FILL(errors, 0) / requests, 0)",
            using_metrics={
                "errors": api.metric_server_error(period=FIVE_MIN, statistic="Sum"),
                "requests": api.metric_count(period=FIVE_MIN, statistic="Sum"),
            },
            period=FIVE_MIN,
            label="5xx %",
        )
        alarm("FiveXx", "5xx", five_xx, 0.5, 1)
        spillover: list[cw.IMetric] = []  # provisioned concurrency is a Lambda alias's; none on ECS
        if mcp.alias is not None:
            spillover.append(
                mcp.alias.metric(
                    "ProvisionedConcurrencySpilloverInvocations", period=FIVE_MIN, statistic="Sum"
                )
            )
            alarm("Spillover", "spillover", spillover[0], 0, 3)
        alarm(
            "Canary",
            "canary",
            _metric("CanarySuccess", "Minimum", service="canary"),
            1,
            2,
            op=cw.ComparisonOperator.LESS_THAN_THRESHOLD,
            missing=cw.TreatMissingData.BREACHING,
        )
        # The dead-letter queues by their fixed names (EnvConfig.queue_name), not by import: a renamed
        # queue (ADR-025) would otherwise change an export another stack's template still reads.
        self.add_dependency(asyncs)
        for construct_id, name in (("JobsDlq", "jobs-dlq"), ("OutboxDlq", "outbox-dlq")):
            visible = cw.Metric(
                namespace="AWS/SQS",
                metric_name="ApproximateNumberOfMessagesVisible",
                dimensions_map={"QueueName": cfg.queue_name(name)},
                statistic="Maximum",
                period=FIVE_MIN,
            )
            alarm(construct_id, name, visible, 0, 1)
        if cfg.models_enabled:  # the account's Bedrock quotas are the first limit a live demo hits (ADR-022)
            slots = [("fast", cfg.models.haiku)] + (
                [("reasoning", cfg.models.sonnet)] if cfg.triage_on else []
            )
            for slot, model_id in slots:
                throttles = cw.Metric(
                    namespace="AWS/Bedrock",
                    metric_name="InvocationThrottles",
                    dimensions_map={"ModelId": model_id},
                    period=FIVE_MIN,
                    statistic="Sum",
                )
                alarm(f"Throttles{slot.title()}", f"bedrock-throttles-{slot}", throttles, 0, 1)
                # Anything else the provider refuses or fails on (access, validation, 5xx): a few in
                # ten minutes is a model gone wrong, and the offline engine is answering instead.
                errors = cw.MathExpression(
                    expression="FILL(client, 0) + FILL(server, 0)",
                    using_metrics={
                        key: cw.Metric(
                            namespace="AWS/Bedrock",
                            metric_name=name,
                            dimensions_map={"ModelId": model_id},
                            period=FIVE_MIN,
                            statistic="Sum",
                        )
                        for key, name in (
                            ("client", "InvocationClientErrors"),
                            ("server", "InvocationServerErrors"),
                        )
                    },
                    period=FIVE_MIN,
                    label="model errors",
                )
                alarm(f"Errors{slot.title()}", f"bedrock-errors-{slot}", errors, 3, 2)
        alarm("OutboxDead", "outbox-dead", _metric("OutboxDead", "Maximum", service="sweeper"), 0, 1)
        hour = Duration.hours(1)
        triage_fail = cw.MathExpression(
            expression=(
                "IF((FILL(sent, 0) + FILL(dead, 0) + FILL(timedout, 0)) > 0, "
                "100 * (FILL(dead, 0) + FILL(timedout, 0)) / (FILL(sent, 0) + FILL(dead, 0) + FILL(timedout, 0)), 0)"
            ),
            using_metrics={
                "dead": _metric("OutboxDeadLettered", period=hour, service="dispatcher", kind="triage_job"),
                "sent": _metric("OutboxSent", period=hour, service="dispatcher", kind="triage_job"),
                "timedout": _metric("TriageTimedOut", period=hour, service="sweeper"),
            },
            period=hour,
            label="triage failure %",
        )
        alarm("TriageFail", "triage-fail", triage_fail, 10, 1)

        # Database saturation: a small burstable instance runs out of CPU, connections or disk before
        # anything else in the system does, and until now nothing said so.
        def rds(name: str, stat: str = "Average") -> cw.Metric:
            return cw.Metric(
                namespace="AWS/RDS",
                metric_name=name,
                dimensions_map={"DBInstanceIdentifier": data.db.instance_identifier},
                statistic=stat,
                period=FIVE_MIN,
            )

        alarm("DbCpu", "db-cpu", rds("CPUUtilization"), 80, 3)
        alarm(
            "DbConnections",
            "db-connections",
            rds("DatabaseConnections", "Maximum"),
            db_connection_alarm_level(cfg.db_instance_class),
            2,
        )
        low_disk = max(2 * GIB, int(0.2 * cfg.db_storage_gb * GIB))  # a fifth of the volume, at least 2 GiB
        alarm(
            "DbStorage",
            "db-storage",
            rds("FreeStorageSpace", "Minimum"),
            low_disk,
            1,
            op=cw.ComparisonOperator.LESS_THAN_THRESHOLD,
        )

        # Queue age: a consumer that has stopped leaves its queue growing old long before a dead-letter
        # queue fills. Triage jobs take about 90 s, so five minutes is stuck; the outbox gets 15.
        ages = {
            name: cw.Metric(
                namespace="AWS/SQS",
                metric_name="ApproximateAgeOfOldestMessage",
                dimensions_map={"QueueName": cfg.queue_name(name)},
                statistic="Maximum",
                period=FIVE_MIN,
            )
            for name in ("jobs", "outbox")
        }
        alarm("JobsAge", "jobs-queue-age", ages["jobs"], 300, 2)
        alarm("OutboxAge", "outbox-queue-age", ages["outbox"], 900, 2)

        # Authentication trouble: refused bearer tokens and failed sign-ins are 4xx at the gateway
        # (throttled callers too), so a burst of them is a client gone wrong or someone guessing.
        alarm(
            "McpClientErrors",
            "mcp-4xx",
            mcp.api.metric_client_error(period=FIVE_MIN, statistic="Sum"),
            100,
            2,
        )
        alarm(
            "AuthClientErrors",
            "auth-4xx",
            auth.api.metric_client_error(period=FIVE_MIN, statistic="Sum"),
            50,
            2,
        )

        dash = cw.Dashboard(self, "Dashboard", dashboard_name=p)
        dash.add_widgets(
            cw.GraphWidget(
                title="Hot path: ToolLatencyMs p95",
                left=[_metric("ToolLatencyMs", "p95", tool=t) for t in HOT_TOOLS],
                width=12,
            ),
            cw.GraphWidget(
                title="Hot path: 5xx % and spillover" if spillover else "Hot path: 5xx %",
                left=[five_xx],
                right=spillover,
                width=12,
            ),
        )
        dash.add_widgets(
            cw.GraphWidget(title="Warm path: triage failure %", left=[triage_fail], width=12),
            cw.GraphWidget(
                title="Cold path: outbox",
                left=[
                    _metric("OutboxBacklog", "Maximum", service="sweeper"),
                    _metric("OutboxDead", "Maximum", service="sweeper"),
                ],
                right=[_metric("WatcherDurationMs", "Maximum", service="watcher")],
                width=12,
            ),
        )
        dash.add_widgets(
            cw.GraphWidget(
                title="Database: CPU % and connections",
                left=[rds("CPUUtilization")],
                right=[rds("DatabaseConnections", "Maximum")],
                width=12,
            ),
            cw.GraphWidget(title="Queues: age of the oldest message (s)", left=list(ages.values()), width=12),
        )
        dash.add_widgets(
            cw.GraphWidget(
                title="Availability: canary",
                left=[_metric("CanarySuccess", "Average", service="canary")],
                right=[_metric("CanaryLatencyMs", "p95", service="canary")],
                width=24,
            )
        )

        # Budgets (DD §25): one account-wide monthly cost budget, e-mailing at each threshold. Account-wide
        # because a tag filter reads $0 until the tag is activated for cost allocation; only one
        # environment's config should list thresholds (dev.yaml), or the e-mails arrive twice.
        if not cfg.budgets_usd:
            return
        budgets.CfnBudget(
            self,
            "Budget",
            budget=budgets.CfnBudget.BudgetDataProperty(
                budget_name="watchfloor-cost",
                budget_type="COST",
                time_unit="MONTHLY",
                budget_limit=budgets.CfnBudget.SpendProperty(amount=max(cfg.budgets_usd), unit="USD"),
                # Usage before credits: on an account paid for by credits, spend net of them reads $0.
                cost_types=budgets.CfnBudget.CostTypesProperty(include_credit=False, include_refund=False),
            ),
            notifications_with_subscribers=[
                budgets.CfnBudget.NotificationWithSubscribersProperty(
                    notification=budgets.CfnBudget.NotificationProperty(
                        comparison_operator="GREATER_THAN",
                        notification_type="ACTUAL",
                        threshold=amount,
                        threshold_type="ABSOLUTE_VALUE",
                    ),
                    subscribers=[
                        budgets.CfnBudget.SubscriberProperty(
                            subscription_type="EMAIL", address=cfg.alert_email
                        )
                    ],
                )
                for amount in cfg.budgets_usd
            ],
        )
