"""One-shot migration Lambda (TD §9.1): applies ``db/migrations`` from inside the VPC.

The deploy pipeline invokes it after ``cdk deploy``. It connects as the schema
owner (``WF_OWNER_DB_SECRET_ARN``) and is idempotent: applied versions are
recorded with checksums, and an edited migration aborts instead of re-running.

Migration 0004 creates ``wf_app`` and ``wf_auth`` without logins. In AWS their
passwords are generated by Secrets Manager (the Data stack), so after migrating
this Lambda enables each login with the password from its secret
(``WF_APP_DB_SECRET_ARN``, ``WF_AUTH_DB_SECRET_ARN``). Re-running it after a
rotation applies the new passwords.

Packaging: the Lambda zip carries the repository's ``db/`` package beside ``workers/``.
"""

from __future__ import annotations

import json
import os
from typing import Any

import asyncpg
from watchfloor_core.db import dsn_from_secret

from . import runtime

ROLE_SECRETS = {"wf_app": "WF_APP_DB_SECRET_ARN", "wf_auth": "WF_AUTH_DB_SECRET_ARN"}


async def set_role_passwords(dsn: str, passwords: dict[str, str]) -> list[str]:
    """Enable login for each role with its password. Quoting is done by Postgres ``format``."""
    conn = await asyncpg.connect(dsn)
    try:
        for role, password in passwords.items():
            if role not in ROLE_SECRETS:
                raise ValueError(f"unexpected role {role}")
            statement = await conn.fetchval(
                "SELECT format('ALTER ROLE %I LOGIN PASSWORD %L', $1::text, $2::text)", role, password
            )
            await conn.execute(statement)
    finally:
        await conn.close()
    return sorted(passwords)


async def _run(dsn: str, passwords: dict[str, str]) -> dict[str, Any]:
    from db.migrate import migrate  # bundled beside this package in the Lambda zip

    applied = await migrate(dsn, verbose=True)
    return {"applied": applied, "logins": await set_role_passwords(dsn, passwords)}


def handler(_event: object, _ctx: object) -> dict[str, Any]:
    dsn = dsn_from_secret(os.environ["WF_OWNER_DB_SECRET_ARN"])
    passwords = {
        role: runtime.secret_field(os.environ[env], "password")
        for role, env in ROLE_SECRETS.items()
        if os.environ.get(env)
    }
    return runtime.run_in_lambda(_run(dsn, passwords))


def main() -> int:
    """The same run as a one-off ECS task (ADR-025, ``scripts/run_task.py``): the result, as the
    Lambda returns it, is the last line on stdout. A failure raises, so the task exits non-zero."""
    runtime.configure_logging()
    print(json.dumps(handler(None, None), default=str), flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
